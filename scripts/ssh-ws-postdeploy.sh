#!/usr/bin/env bash
# ABESS's own SSH-WS host bootstrap, no X-NET proprietary code.
# Run ONLY as root on the intended Ubuntu/Debian host, after the panel
# has been deployed and its HTTPS ping is healthy.
set -Eeuo pipefail
trap 'echo "[ABESS SSH-WS] host bootstrap failed on line $LINENO" >&2' ERR
[[ "$EUID" -eq 0 ]] || { echo "Root required" >&2; exit 1; }
[[ "$(pwd)" = "$HOME/abessvpn-server" ]] || { echo "Run inside root home abessvpn-server" >&2; exit 1; }
[[ -f .env && -f scripts/install-ssh-ws.sh && -f scripts/bootstrap-ssh-ws-node.mjs ]] || { echo "Missing ABESS deployment" >&2; exit 1; }
[[ -f /etc/ssh/ssh_host_ed25519_key.pub && -x /usr/sbin/sshd ]] || { echo "OpenSSH Ed25519 key required" >&2; exit 1; }
set -a
# .env contains JSON-quoted strings which are valid safe shell values.
# It is a root-only file generated by our trusted deployment workflow.
source .env
set +a
[[ "${VPN_DOMAIN:-}" =~ ^[a-zA-Z0-9.-]+$ ]] || { echo "Invalid VPN domain" >&2; exit 1; }
[[ "${SSH_WS_HOST:-}" =~ ^[a-zA-Z0-9.-]+$ ]] || { echo "Invalid VPS IP/name" >&2; exit 1; }
command -v docker >/dev/null && docker compose exec -T api node --version >/dev/null || {
  echo "ABESS API container must be running before SSH-WS bootstrap" >&2
  exit 1
}
echo '[ABESS SSH-WS] Installing Node.js 22 on the Ubuntu host (only if absent)...'
if ! command -v node >/dev/null 2>&1 || [[ "$(node -p 'Number(process.versions.node.split(".")[0])')" -lt 22 ]]; then
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl gnupg
  NODE_SETUP="$(mktemp /root/.abess-node22.XXXXXX.sh)"
  trap 'rm -f "$NODE_SETUP"' EXIT
  curl --fail --silent --show-error --location 'https://deb.nodesource.com/setup_22.x' -o "$NODE_SETUP"
  bash "$NODE_SETUP"
  rm -f "$NODE_SETUP"
  apt-get install -y nodejs
fi
[[ "$(node -p 'Number(process.versions.node.split(".")[0])')" -ge 22 ]] || { echo "Node 22 installation failed" >&2; exit 1; }
echo '[ABESS SSH-WS] Installing Node dependencies in isolated /opt/abess-panel checkout...'
install -d -m 0755 /opt/abess-panel
rsync -a \
 --exclude '.env' --exclude '.env.*' --exclude '.deploy*' \
 --exclude 'data/' --exclude 'deployment-backups/' \
 --exclude 'INITIAL_ADMIN_CREDENTIALS.txt' --exclude '.initial-admin-credentials.new' \
 --exclude 'node_modules/' --exclude 'dist/' --exclude '.git/' \
 ./ /opt/abess-panel/
(cd /opt/abess-panel && npm ci --omit=dev --no-audit --no-fund)
install -d -m 0700 /etc/abess-ssh-ws
BOOTSTRAP=/etc/abess-ssh-ws/node-bootstrap.json
NODE_KEY_SOURCE=/etc/abess-ssh-ws/node-key-source
if [[ ! -s "$BOOTSTRAP" ]]; then
  echo '[ABESS SSH-WS] Registering new managed node through authenticated panel API...'
  FINGERPRINT="$(ssh-keygen -lf /etc/ssh/ssh_host_ed25519_key.pub -E sha256 | awk '{print $2}')"
  [[ "$FINGERPRINT" =~ ^SHA256:[A-Za-z0-9+/]{43}=?$ ]] || exit 1
  umask 077
  docker compose exec -T \
    -e "ABESS_NODE_HOST=$SSH_WS_HOST" \
    -e "ABESS_SSH_SNI=$VPN_DOMAIN" \
    -e "ABESS_SSH_FINGERPRINT=$FINGERPRINT" \
    api node /app/scripts/bootstrap-ssh-ws-node.mjs > "$BOOTSTRAP"
fi
chmod 0600 "$BOOTSTRAP"
VPN_NODE_ID="$(node -e 'const j=require(process.argv[1]);if(!/^[a-f0-9-]{36}$/.test(j.id))process.exit(2);process.stdout.write(j.id)' "$BOOTSTRAP")"
EDGE_SNI="${SSH_WS_EDGE_HOST:-$VPN_DOMAIN}"
[[ "$EDGE_SNI" =~ ^[a-z0-9.-]+$ ]] || { echo "Invalid SSH_WS_EDGE_HOST" >&2; exit 1; }
FINGERPRINT="$(ssh-keygen -lf /etc/ssh/ssh_host_ed25519_key.pub -E sha256 | awk '{print $2}')"
CURRENT_NODE_KEY="$(node -e 'const fs=require("node:fs");const j=JSON.parse(fs.readFileSync(process.argv[1],"utf8"));if(!/^[a-f0-9]{64}$/.test(j.key||""))process.exit(2);process.stdout.write(j.key)' "$BOOTSTRAP")"
EDGE_RESULT="$(docker compose exec -T \
  -e "ABESS_NODE_ID=$VPN_NODE_ID" \
  -e "ABESS_SSH_SNI=$EDGE_SNI" \
  -e "ABESS_SSH_FINGERPRINT=$FINGERPRINT" \
  -e "ABESS_CURRENT_NODE_KEY=$CURRENT_NODE_KEY" \
  api node /app/scripts/update-ssh-ws-edge.mjs)"
REPAIRED_NODE_KEY="$(printf '%s' "$EDGE_RESULT" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const j=JSON.parse(s);if(!/^[a-f0-9]{64}$/.test(j.key||""))process.exit(2);process.stdout.write(j.key)})')"
node - "$BOOTSTRAP" "$REPAIRED_NODE_KEY" <<'NODE'
const fs=require('node:fs');
const file=process.argv[2],key=process.argv[3];
const data=JSON.parse(fs.readFileSync(file,'utf8'));
data.key=key;
fs.writeFileSync(file,JSON.stringify(data)+'\n',{mode:0o600});
NODE
printf '%s\n' "$REPAIRED_NODE_KEY" > "$NODE_KEY_SOURCE"
chmod 0600 "$NODE_KEY_SOURCE"
echo '[ABESS SSH-WS] Verifying node API credential before starting reconciler...'
NODE_KEY="$(cat "$NODE_KEY_SOURCE")"
DESIRED_STATUS="$(curl --silent --show-error --max-time 12 -o /tmp/abess-desired.json -w '%{http_code}' \
  -H "Authorization: Bearer $NODE_KEY" "https://$VPN_DOMAIN/api/v1/nodes/$VPN_NODE_ID/ssh-ws/desired" || true)"
if [[ "$DESIRED_STATUS" != "200" ]]; then
  echo "[ABESS SSH-WS] Node API credential rejected with HTTP $DESIRED_STATUS; rotating managed node key..." >&2
  NEW_KEY="$(docker compose exec -T \
    -e "ABESS_NODE_ID=$VPN_NODE_ID" \
    api node /app/scripts/rotate-ssh-ws-node-key.mjs)"
  [[ "$NEW_KEY" =~ ^[a-f0-9]{64}$ ]] || { echo "Invalid rotated node key" >&2; exit 1; }
  printf '%s\n' "$NEW_KEY" > "$NODE_KEY_SOURCE"
  chmod 0600 "$NODE_KEY_SOURCE"
  DESIRED_STATUS="$(curl --silent --show-error --max-time 12 -o /tmp/abess-desired.json -w '%{http_code}' \
    -H "Authorization: Bearer $NEW_KEY" "https://$VPN_DOMAIN/api/v1/nodes/$VPN_NODE_ID/ssh-ws/desired" || true)"
fi
[[ "$DESIRED_STATUS" == "200" ]] || {
  echo "[ABESS SSH-WS] Desired-state endpoint still failing: HTTP $DESIRED_STATUS" >&2
  cat /tmp/abess-desired.json >&2 || true
  rm -f /tmp/abess-desired.json
  exit 1
}
rm -f /tmp/abess-desired.json
echo '[ABESS SSH-WS] Node credential verified.'
echo '[ABESS SSH-WS] Configuring independent SSHD, gateway and reconciler...'
(cd /opt/abess-panel && CONTROL_API_BASE_URL="http://127.0.0.1:3000" \
 VPN_NODE_ID="$VPN_NODE_ID" VPN_NODE_KEY_FILE="$NODE_KEY_SOURCE" \
 bash scripts/install-ssh-ws.sh)
GID="$(id -g abess-gateway)"
if grep -q '^SSH_WS_GATEWAY_GID=' .env; then
  sed -i "s/^SSH_WS_GATEWAY_GID=.*/SSH_WS_GATEWAY_GID=$GID/" .env
else printf '\nSSH_WS_GATEWAY_GID=%s\n' "$GID" >> .env
fi
chmod 0600 .env
echo '[ABESS SSH-WS] Applying secure Caddy Unix socket group membership...'
docker compose up -d --no-deps --force-recreate caddy
for name in abess-ssh-ws-sshd abess-ssh-ws-gateway abess-ssh-ws-reconciler; do
 systemctl is-active --quiet "$name" || {
   journalctl -u "$name" --no-pager --lines 30 >&2 || true
   echo "$name is not running" >&2
   exit 1
 }
done
echo '[ABESS SSH-WS] Checking gateway policy and HTTPS API status...'
READY=no
for attempt in {1..20}; do
  if curl --silent --show-error --max-time 5 --unix-socket /var/lib/abess-ssh-ws/socket/gateway.sock http://localhost/healthz | grep -q '"policyReady":true'; then READY=yes; break; fi
  sleep 2
done
[[ "$READY" = yes ]] || {
  journalctl -u abess-ssh-ws-reconciler --lines 30 --no-pager >&2 || true
  echo 'Gateway policy did not become ready. Check panel API and agent key.' >&2; exit 1
}
curl --fail --silent --show-error --max-time 10 "https://$VPN_DOMAIN/api/v1/ping" | grep -q '"ok":true'
docker compose exec -T caddy test -S /var/run/abess-ssh-ws/gateway.sock || {
 echo 'Caddy container cannot access private SSH-WS socket' >&2; exit 1;
}
# The path is intentionally not a functional client licence; it must be refused.
STATUS="$(curl --silent --show-error --max-time 10 -o /dev/null -w '%{http_code}' "https://$VPN_DOMAIN/ssh-ws/no-such-client")"
[[ "$STATUS" = '404' ]] || { echo "Unexpected WSS proxy test response HTTP $STATUS" >&2; exit 1; }
echo 'ABESS_SSH_WS_INSTALLATION=SUCCESS'
echo "ABESS_SSH_WS_SNI=$EDGE_SNI"
echo 'ABESS_SSH_WS_PORT=443'
echo 'ABESS_SSH_WS_PATH=/ssh-ws/<unique-client-secret>'
echo "ABESS_SSH_WS_NODE_ID=$VPN_NODE_ID"
